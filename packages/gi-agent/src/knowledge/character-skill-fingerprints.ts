/**
 * V31 F9 — Character Skill Fingerprint (CSF) runtime loader.
 *
 * Loads the pre-computed 256-dim CSF vectors generated by
 * `scripts/ops/generate-character-skill-fingerprints.ts` and provides
 * a lookup function with degraded OOD fallback.
 *
 * The artifact is a single ~150 KB JSON file embedded at build time;
 * loading is lazy (first call triggers read from disk) and the map is
 * cached for the lifetime of the process.
 */

import { readFileSync } from "node:fs"
import { join, dirname } from "node:path"
import { fileURLToPath } from "node:url"

export const CSF_DIM = 256

interface CsfArtifact {
  version: string
  dim: number
  fingerprints: Record<string, number[]>
}

let _fingerprints: Map<number, number[]> | null = null

const __dirname = dirname(fileURLToPath(import.meta.url))
const DEFAULT_CSF_PATH = join(__dirname, "..", "..", "output", "character-skill-fingerprints.json")

function loadCsfArtifactOrNull(path?: string): Map<number, number[]> | null {
  try {
    const resolvedPath = path ?? DEFAULT_CSF_PATH
    const text = readFileSync(resolvedPath, "utf-8")
    const raw = JSON.parse(text) as CsfArtifact
    const map = new Map<number, number[]>()
    for (const [key, vec] of Object.entries(raw.fingerprints)) {
      map.set(Number(key), vec)
    }
    return map
  } catch {
    return null
  }
}

export function loadSkillFingerprints(path?: string): Map<number, number[]> | null {
  if (_fingerprints) return _fingerprints
  _fingerprints = loadCsfArtifactOrNull(path)
  return _fingerprints
}

export function getSkillFingerprint(definitionId: number): number[] {
  const map = loadSkillFingerprints()
  const fp = map?.get(definitionId)
  if (fp) return fp
  return degradedFingerprint(definitionId)
}

/**
 * Degraded OOD fallback: returns a 256-dim vector with only Block-1
 * element/weapon hints filled in via definition_id convention (1<E>NN).
 * All other dimensions are 0.
 */
export function degradedFingerprint(definitionId: number): number[] {
  const fp = new Array(256).fill(0)

  // Try to extract element from definition_id (1<E>NN convention)
  if (definitionId >= 1000) {
    const elementDigit = Math.floor(definitionId / 100) % 10
    if (elementDigit >= 1 && elementDigit <= 7) {
      fp[elementDigit - 1] = 1 // element one-hot [0-6]
    }
  }

  return fp
}

export function clearCsfCache(): void {
  _fingerprints = null
}
