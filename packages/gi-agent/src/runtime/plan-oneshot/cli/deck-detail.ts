/**
 * deck-detail — plan:author user prompt 的牌表详情渲染（纯函数，零 I/O）。
 *
 * 技能行带 skill defId（`#17033`）：LLM 写 then.skill_def_id 的取数来源，同类型
 * 多战技角色（纳西妲 17032/17033、纯水精灵 22012/22013）靠它指名具体技能。
 * skillId 由调用方按**名字**对齐（资产技能记录 name → id，与 deck-context 的
 * `skills[].name` 同源），不做顺序猜测，避免同类型多变体错配；对不上就不渲染 id。
 */

import type { GameData } from "@gi-tcg/core"
import type { DeckContext } from "@gi-tcg/llm-deck-analyzer"
import { coreTagsOf, formatCost, oneLine } from "./modules.js"

/** 牌表详情渲染所需上下文（describeDeckDetail 从 DeckContext 截取） */
export type DeckDetailContext = Pick<
  DeckContext,
  "characterFullInfo" | "cards" | "entityDescriptions" | "generatedHandCardDescriptions"
>

/** deck-context 的技能类型展示标签 → 计划 skill_type 词汇（validate.ts SKILL_TYPES；被动/载具原样） */
const SKILL_TYPE_PLAN_NAME: Record<string, string> = {
  普通攻击: "normal_attack",
  元素战技: "elemental_skill",
  元素爆发: "burst",
  被动技能: "passive",
  战技: "technique",
}

/** 渲染牌表详情：角色技能（带 defId）→ 卡牌（带 core 短名 tag）→ 衍生物/生成手牌 */
export function renderDeckDetail(
  ctx: DeckDetailContext,
  gameData: GameData,
  skillIdsOf: (charDefId: number) => ReadonlyMap<string, number>,
): string {
  const lines: string[] = []
  lines.push("Characters:")
  for (const ch of ctx.characterFullInfo) {
    lines.push(`  ${ch.id} ${ch.name} | ${ch.elements.join("/")} | HP ${ch.hp} | max energy ${ch.maxEnergy}`)
    const skillIds = skillIdsOf(ch.id)
    for (const s of ch.skills) {
      const skillType = SKILL_TYPE_PLAN_NAME[s.type] ?? s.type
      const skillId = skillIds.get(s.name)
      const idNote = skillId !== undefined ? `#${skillId} ` : ""
      lines.push(`    - ${skillType} ${idNote}"${s.name}" cost ${formatCost(s.playCost)}: ${oneLine(s.description)}`)
    }
  }
  const counts = new Map<number, number>()
  for (const c of ctx.cards) counts.set(c.id, (counts.get(c.id) ?? 0) + 1)
  const seen = new Set<number>()
  lines.push("Cards (with copy counts):")
  for (const c of ctx.cards) {
    if (seen.has(c.id)) continue
    seen.add(c.id)
    const play = c.playingDescription ? ` (when played: ${oneLine(c.playingDescription)})` : ""
    const tags = coreTagsOf(c.id, c.tags, gameData)
    const tagNote = tags.length > 0 ? ` | tags: ${tags.join("/")}` : ""
    lines.push(`  ${c.id} ${c.name} ×${counts.get(c.id) ?? 1} | ${c.type}/${c.subtype} | cost ${formatCost(c.playCost)}${tagNote}: ${oneLine(c.description)}${play}`)
  }
  if (ctx.entityDescriptions.size > 0) {
    lines.push("Summons/statuses referenced by skills and cards:")
    for (const [name, desc] of ctx.entityDescriptions) {
      lines.push(`  - ${name}: ${oneLine(desc)}`)
    }
  }
  if (ctx.generatedHandCardDescriptions.size > 0) {
    lines.push("Cards generated by skills:")
    for (const [name, desc] of ctx.generatedHandCardDescriptions) {
      lines.push(`  - ${name}: ${oneLine(desc)}`)
    }
  }
  return lines.join("\n")
}
